function getDeadlinesForMonth(monthKey) {
    const deadlines = [];
    const monthData = scheduleData[monthKey];
    const monthNamesGenitive = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
                                'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

    if (monthData) {
        const [, month] = monthKey.split('-');
        Object.keys(monthData)
            .sort((a, b) => parseInt(a) - parseInt(b))
            .forEach(day => {
                monthData[day].forEach(event => {
                    if (event.type === 'test_deadline_soft' || event.type === 'test_deadline') {
                        const meta = getSubjectMeta(event);
                        deadlines.push({
                            date: `${parseInt(day)} ${monthNamesGenitive[parseInt(month) - 1]}`,
                            subject: event.title,
                            desc: event.description || (event.type === 'test_deadline' ? 'Экзаменационный тест' : 'Контрольная работа'),
                            type: event.type,
                            subjectKey: meta.key,
                            exact: true
                        });
                    }
                });
            });
    }

    const extras = importantDeadlines[monthKey] || [];
    extras.forEach(item => deadlines.push({ exact: false, ...item }));

    return deadlines;
}

